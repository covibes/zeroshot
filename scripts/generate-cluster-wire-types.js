#!/usr/bin/env node
/**
 * Generates TypeScript wire types for the `@the-open-engine/zeroshot/cluster` client from the
 * authoritative Cluster Protocol v1 JSON Schema / OpenRPC artifacts under
 * `protocol/openengine-cluster/v1/`. Hand-maintained duplicate DTOs are forbidden -- every wire
 * type used by the client is generated here.
 *
 * Usage:
 *   node scripts/generate-cluster-wire-types.js          # regenerate committed output
 *   node scripts/generate-cluster-wire-types.js --check  # regenerate to a temp dir, diff, exit 1 on drift
 */
'use strict';

const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { compileFromFile } = require('json-schema-to-typescript');

const repoRoot = path.resolve(__dirname, '..');
const protocolDir = path.join(repoRoot, 'protocol', 'openengine-cluster', 'v1');
const outDir = path.join(repoRoot, 'src', 'cluster', 'generated');

const GENERATED_HEADER =
  '// GENERATED by scripts/generate-cluster-wire-types.js -- do not edit.\n' +
  '// Source: protocol/openengine-cluster/v1/{schema,graph.schema,compiled-ir.schema,worker.schema,openrpc}.json\n';

const STYLE = {
  bracketSpacing: false,
  printWidth: 100,
  semi: true,
  singleQuote: true,
  tabWidth: 2,
  trailingComma: 'es5',
  useTabs: false,
};

const SCHEMA_TARGETS = [
  { file: 'schema.json', out: 'wire-types.ts' },
  { file: 'graph.schema.json', out: 'graph-schema.ts' },
  { file: 'compiled-ir.schema.json', out: 'compiled-ir-schema.ts' },
  { file: 'worker.schema.json', out: 'worker-schema.ts' },
];

/** Converts an OpenRPC method name (e.g. `agent/attach`) into a PascalCase type-name segment. */
function methodNamePascalCase(method) {
  return method
    .split('/')
    .map((segment) => segment.charAt(0).toUpperCase() + segment.slice(1))
    .join('');
}

function compileSchema(target) {
  return compileFromFile(path.join(protocolDir, target.file), {
    cwd: protocolDir,
    bannerComment: GENERATED_HEADER,
    unreachableDefinitions: true,
    style: STYLE,
  });
}

function generateMethodsSource(openrpc) {
  const unaryMethods = [
    'initialize',
    'plan',
    'apply',
    'get',
    'update',
    'stop',
    'retry',
    'resubmit',
    'delete',
  ];
  const subscriptionMethods = ['watch', 'logs', 'agent/attach'];
  const allMethods = openrpc.methods.map((method) => method.name);

  for (const method of [...unaryMethods, ...subscriptionMethods]) {
    if (!allMethods.includes(method)) {
      throw new Error(`openrpc.json is missing method "${method}" expected by the TS client`);
    }
  }
  if (allMethods.length !== unaryMethods.length + subscriptionMethods.length) {
    throw new Error(
      `openrpc.json defines ${allMethods.length} methods but the TS client only accounts for ` +
        `${unaryMethods.length + subscriptionMethods.length}; update generate-cluster-wire-types.js`
    );
  }

  const lines = [];
  lines.push(GENERATED_HEADER);
  lines.push("import type * as Wire from './wire-types.js';");
  lines.push('');
  lines.push('/** Every unary (request/response) Cluster Protocol v1 method name. */');
  lines.push(
    'export type UnaryMethod =\n  ' + unaryMethods.map((m) => `'${m}'`).join('\n  | ') + ';'
  );
  lines.push('');
  lines.push('/** Every subscription-establishing Cluster Protocol v1 method name. */');
  lines.push(
    'export type SubscriptionMethod =\n  ' +
      subscriptionMethods.map((m) => `'${m}'`).join('\n  | ') +
      ';'
  );
  lines.push('');
  lines.push('/** Every Cluster Protocol v1 JSON-RPC method name. */');
  lines.push('export type MethodName = UnaryMethod | SubscriptionMethod;');
  lines.push('');

  lines.push('/** Per-method request params type, keyed by method name. */');
  lines.push('export interface MethodParams {');
  for (const method of [...unaryMethods, ...subscriptionMethods]) {
    const pascal = methodNamePascalCase(method);
    lines.push(`  '${method}': Wire.${pascal}Params;`);
  }
  lines.push('}');
  lines.push('');

  lines.push('/** Per-method success result type, keyed by method name. */');
  lines.push('export interface MethodResult {');
  for (const method of [...unaryMethods, ...subscriptionMethods]) {
    const pascal = methodNamePascalCase(method);
    lines.push(`  '${method}': Wire.${pascal}Result;`);
  }
  lines.push('}');
  lines.push('');

  lines.push('export const UNARY_METHODS: readonly UnaryMethod[] = [');
  for (const method of unaryMethods) lines.push(`  '${method}',`);
  lines.push('];');
  lines.push('');
  lines.push('export const SUBSCRIPTION_METHODS: readonly SubscriptionMethod[] = [');
  for (const method of subscriptionMethods) lines.push(`  '${method}',`);
  lines.push('];');
  lines.push('');

  return lines.join('\n') + '\n';
}

async function generateAll(targetDir) {
  fs.mkdirSync(targetDir, { recursive: true });

  for (const target of SCHEMA_TARGETS) {
    const source = await compileSchema(target);
    fs.writeFileSync(path.join(targetDir, target.out), source);
  }

  const openrpc = JSON.parse(fs.readFileSync(path.join(protocolDir, 'openrpc.json'), 'utf8'));
  const methodsSource = generateMethodsSource(openrpc);
  fs.writeFileSync(path.join(targetDir, 'methods.ts'), methodsSource);
}

function readDirState(dir) {
  const state = new Map();
  if (!fs.existsSync(dir)) return state;
  for (const entry of fs.readdirSync(dir)) {
    if (!entry.endsWith('.ts')) continue;
    state.set(entry, fs.readFileSync(path.join(dir, entry), 'utf8'));
  }
  return state;
}

async function main() {
  const check = process.argv.includes('--check');

  if (!check) {
    await generateAll(outDir);
    console.log(`Generated cluster wire types in ${path.relative(repoRoot, outDir)}`);
    return;
  }

  const tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), 'zeroshot-cluster-wire-types-'));
  try {
    await generateAll(tmpDir);
    const committed = readDirState(outDir);
    const fresh = readDirState(tmpDir);

    const allFiles = new Set([...committed.keys(), ...fresh.keys()]);
    const drift = [];
    for (const file of allFiles) {
      if (committed.get(file) !== fresh.get(file)) drift.push(file);
    }

    if (drift.length > 0) {
      console.error('Cluster wire types are out of date. Run `npm run generate:cluster-types`.');
      console.error('Drifted files:', drift.join(', '));
      process.exitCode = 1;
      return;
    }
    console.log('Cluster wire types are up to date.');
  } finally {
    fs.rmSync(tmpDir, { recursive: true, force: true });
  }
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
